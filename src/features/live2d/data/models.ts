export function getCharacter(index: number): CharacterMetadata {
  const safeIndex = Math.max(0, Math.min(index, MYGO_CHARACTERS.length - 1));
  return MYGO_CHARACTERS[safeIndex] ?? MYGO_CHARACTERS[0];
}

export function getOutfit(characterIndex: number, outfitIndex: number): OutfitMetadata {
  const char = getCharacter(characterIndex);
  const safeOutfitIndex = Math.max(0, Math.min(outfitIndex, char.outfits.length - 1));
  return char.outfits[safeOutfitIndex] ?? char.outfits[0];
}
