export function languageForPath(path: string): string {
  const dot = path.lastIndexOf(".");
  if (dot < 0 || dot === path.length - 1) return "plaintext";
  const ext = path.slice(dot + 1).toLowerCase();
  return EXTENSION_LANGUAGE[ext] ?? "plaintext";
}
